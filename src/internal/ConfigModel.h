#pragma once

#include "HalTypes.h"

namespace hal {

/**
 * @brief 内部已解析配置模型。
 *
 * 公共 C ABI 那边的 `HalCConfig` 是**扁平、定长、跨进程**的传输格式；
 * 这里是 HAL 内部消化过的版本，两者不是一回事，也不该互相 include。
 *
 * ## 两层模型（L1 / L2）
 *
 * 保留旧工程的两层划分，但**合并成每槽一个结构体**：旧工程有
 * `HalAxisBind` + `std::vector<HalAxisL1>` 等三套并行数组，靠
 * `slave_pos` 手动对齐，L1/L2 配对成了运行期检查。合并后配对是编译期
 * 事实。L1/L2 的区别靠**字段分组与注释**保留，不再靠数组分离。
 *
 *   - **L1 设备参数**：设备的身份与固有行为（从站位置、编码器类型、
 *     每转脉冲数…）。换一台同型号设备要改的就是这些。
 *   - **L2 机床参数**：机床侧赋予的含义（逻辑轴号、单位当量、方向
 *     取反、PLC 地址段…）。换一台设备**不该**改这些。
 *
 * ## 约束
 *
 * 本头文件被**配置库**和**实时库**同时包含，而配置库是零硬件依赖、
 * 零分配的。因此这里只能放 POD，且不得使用 `std::vector` 等容器——
 * 槽位数组一律定长。
 */

// ==================== 数字量 IO / 机床操作面板 ====================

/**
 * @brief IO 槽的种类。
 *
 * 普通 IO 模块与机床操作面板（MCP）**物理上是同一类东西**——都是挂在
 * 总线上的数字量从站，输入按键/开关、输出指示灯/继电器。所以两者共用
 * 一个 `IDIO` 接口、共用一套字节图契约。
 *
 * 区别只有两点，都不构成接口差异：
 *   1. PLC 地址域的段分配方式（由配置决定）；
 *   2. HMI 怎么解读那几字节（那是 HMI 的事，HAL 不解读）。
 */
enum class IoSlotKind : uint8_t {
    Module = 0,   ///< 普通数字量 IO 模块
    Panel,        ///< 机床操作面板
};

/**
 * @brief 单个 IO 槽的已解析配置（L1 设备参数 + L2 机床参数）。
 *
 * 一个槽对应总线上一台数字量从站。输入/输出**字节数不在配置里**——
 * 那是 Entry 布局决定的硬件事实，装配时由驱动读出来，通过
 * `IDIO::inputBytes()` / `outputBytes()` 呈现。
 */
struct DioCfgDev {
    // ---- 身份 / 绑定（L1）----

    /// 绑定的从站位置（总线拓扑，运行期不变）
    int slave_pos = -1;

    /// 槽种类：普通模块还是操作面板
    IoSlotKind kind = IoSlotKind::Module;

    /// 面板型号（仅 kind == Panel 时有意义）。
    /// HAL **不解读**这个数字，只透传给 HMI——按键与指示灯的语义布局
    /// 随型号而变，那是显示层的事。
    int panel_type = 0;

    // ---- PLC 域映射（L2）----

    /// 输入段在 PLC 域 X 里的起始**字节**地址（不是位地址）
    int x_start = 0;

    /// 输出段在 PLC 域 Y 里的起始**字节**地址
    int y_start = 0;
};

} // namespace hal
